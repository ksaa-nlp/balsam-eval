"""LLM Judge specialized for Generative (open-ended) tasks."""

from src.llm_judger.base_llm_judge import BaseLLMJudge


class GenerativeLLMJudge(BaseLLMJudge):
    """
    LLM Judge specialized for Generative (open-ended) tasks.
    
    Key differences from MCQ:
    - Uses continuous 0-1 scoring for nuanced evaluation
    - More detailed rubric for partial credit
    - Focuses on semantic similarity, not exact matching
    """

    def get_evaluation_prompt(self) -> str:
        """Get generative-specific evaluation prompt with binary scoring."""
        return """You are an impartial and expert judge evaluating the quality of \
text generated by another AI model.

Your task is to score the generated output based on the original prompt and a \
provided ground truth answer, following a specific scoring rubric.

You will be provided with three pieces of information:
1. The original prompt given to the generative model.
2. The ground truth answer, representing the ideal or expected output.
3. The actual output generated by the generative model.

Evaluate the generated output by comparing it to the ground truth, considering how well it addresses the original prompt.

**Scoring Rubric:**
Assign a number between 0 and 1 based on correctness and completeness. Decimal scores are allowed.
* **0.0:** Completely wrong, irrelevant, or unrelated to the prompt and ground truth.
* **0.25:** Attempts to answer but contains major errors or omissions.
* **0.5:** Partially correct but misses important information or contains meaningful errors.
* **0.75:** Mostly correct with only minor errors or omissions.
* **1.0:** Fully correct and adequately answers the original prompt. Differences in wording, formatting, or additional relevant information are acceptable when they do not change the meaning or factual correctness.

**Output Format:**
Your output must be *only* a JSON object containing two keys:
1. `score`: A number between 0 and 1, inclusive, based on the rubric above.
2. `explanation`: A brief, concise string explaining *why* you assigned that score, referencing the differences or similarities between the generated output and the ground truth in the context of the prompt.

**Example Output JSON:**
```json
{
  "score": 0.85,
  "explanation": "The generated output is accurate and complete, closely matching the ground truth."
}```"""

    def normalize_score(self, raw_score: float) -> float:
        """
        Validate score on the 0-1 scale.
        """
        if raw_score is None:
            return 0.0
        try:
            score = float(raw_score)
        except (TypeError, ValueError):
            return 0.0
        if not 0.0 <= score <= self.get_max_score():
            return 0.0
        return round(score, 5)

    def get_max_score(self) -> float:
        """Generative uses a continuous 0-1 scoring scale."""
        return 1.0
